import type { ScanResult } from "../types.js";

export function renderMarkdownReport(results: ScanResult[]): string {
  const reachable = results.filter(
    ({ reachability }) => reachability.verdict === "REACHABLE",
  ).length;
  const unknown = results.filter(
    ({ reachability }) => reachability.verdict === "UNKNOWN",
  ).length;
  const lines = [
    "## reachfix vulnerability scan",
    "",
    `Found **${results.length}** vulnerable package/advisory finding(s): ${reachable} reachable, ${unknown} unknown.`,
    "",
    "| Package | Advisory | Reachability | Evidence |",
    "| --- | --- | --- | --- |",
  ];

  for (const { dependency, advisory, reachability } of results) {
    const evidence = reachability.evidence[0]
      ? `\`${escapeMarkdown(reachability.evidence[0].filePath)}\` — ${escapeMarkdown(reachability.reason)}`
      : escapeMarkdown(reachability.reason);
    const advisoryLabel = advisory.summary
      ? `${escapeMarkdown(advisory.id)}: ${escapeMarkdown(advisory.summary)}`
      : escapeMarkdown(advisory.id);
    lines.push(
      `| \`${escapeMarkdown(`${dependency.name}@${dependency.version}`)}\` | [${advisoryLabel}](https://osv.dev/vulnerability/${encodeURIComponent(advisory.id)}) | **${reachability.verdict}** | ${evidence} |`,
    );
  }
  lines.push("", "_Generated by reachfix._");
  return `${lines.join("\n")}\n`;
}

function escapeMarkdown(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}
